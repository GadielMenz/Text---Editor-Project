// built once per character and shared by every PadItem holding that character, do not free
static bool* glyph_cache[GLYPH_COUNT]={NULL};


// returns font_h x font_w pixel data for c, or NULL if c has no glyph
bool* get_char_pixel_data(char c){
if(c<' ' || c>'~') return NULL;

size_t index=c-' ';
if(glyph_cache[index]!=NULL) return glyph_cache[index];

bool* pixel_data=calloc(font_w*font_h,sizeof(bool));
if(pixel_data==NULL) return NULL;
bool (*pixels)[font_w]=(bool (*)[font_w])pixel_data;

// biggest whole scale that fits, centered in the cell
size_t scale=font_w/GLYPH_W < font_h/GLYPH_H ? font_w/GLYPH_W : font_h/GLYPH_H;
size_t offset_x=(font_w-GLYPH_W*scale)/2;
size_t offset_y=(font_h-GLYPH_H*scale)/2;

for (size_t gy = 0; gy < GLYPH_H; gy++)
{
    for (size_t gx = 0; gx < GLYPH_W; gx++)
    {
        if(glyphs[index][gy][gx]!='#') continue;

        for (size_t y = 0; y < scale; y++)
        {
            for (size_t x = 0; x < scale; x++)
            {
                pixels[offset_y+gy*scale+y][offset_x+gx*scale+x]=true;
            }
        }
    }
}

glyph_cache[index]=pixel_data;
return pixel_data;
}


void scratch_pad_init(){
set_up_cursor();    
head=get_cursor();
tail=head;
}


PadItem* add_item_to_pad(char data){
PadItem *cur= get_cursor();

PadItem* new_item= calloc(1,sizeof(PadItem));
new_item->data=data;

if(head==tail){
    head=new_item;
}
PadItem* last_item_prev=cur->prev;
cur->prev=new_item;
new_item->prev=last_item_prev;
new_item->next=cur;
if(last_item_prev!=NULL)last_item_prev->next=new_item;

new_item->pixel_data=get_char_pixel_data(data);



return new_item;
}



